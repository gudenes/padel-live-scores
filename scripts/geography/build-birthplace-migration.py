"""Build the versioned migration from the reviewed INE snapshot. No database access."""
import json
import unicodedata
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
data = json.loads((ROOT / 'apps/ops/src/lib/scouting/intelligence/geography/ine-2026.json').read_text())
import re

def key(s):
    s = ''.join(c for c in unicodedata.normalize('NFD', s) if not '\u0300' <= c <= '\u036f')
    return re.sub(r'\s+', ' ', s.lower().translate(str.maketrans({'’': "'", '‘': "'", '`': "'"}))).strip()
aliases = {}
for m in data['municipalities']:
    names = [m['name'], *m['name'].split('/')]
    for name in names[:]:
        match = re.match(r"^(.+),\s*(L'|La|Les|El|Els|Los|Las|O|A|Os|As)$", name, re.I)
        if match: names.append(match[2] + ('' if match[2].endswith("'") else ' ') + match[1])
    for name in names: aliases[(key(name), m['id'])] = 'exact'
for name, id in {'gerona':'17079','lerida':'25120','hospitalet de llobregat':'08101','la coruna':'15030','seville':'41091'}.items(): aliases[(name,id)] = 'alias'
rows = [{'name_key': k, 'municipality_id': id, 'method': method} for (k,id),method in aliases.items()]
schema = (ROOT / 'scripts/geography/birthplace-schema.sql').read_text()
sql = schema.replace('-- MUNICIPALITY_SEED', "insert into public.birthplace_municipalities (id,name,province_code,region_code) select id,name,province,region from jsonb_to_recordset($municipalities$" + json.dumps(data['municipalities'], ensure_ascii=False, separators=(',',':')) + "$municipalities$::jsonb) as x(id text,name text,province text,region text);\n")
sql = sql.replace('-- ALIAS_SEED', "insert into public.birthplace_aliases (name_key,municipality_id,method) select name_key,municipality_id,method from jsonb_to_recordset($aliases$" + json.dumps(rows, ensure_ascii=False, separators=(',',':')) + "$aliases$::jsonb) as x(name_key text,municipality_id text,method text);\n")
out=ROOT/'supabase/migrations/20261119140000_normalize_player_birthplaces.sql'
out.write_text('-- Generated by scripts/geography/build-birthplace-migration.py\n-- INE snapshot SHA256: '+data['sha256']+'\n'+sql)
print(out, len(sql), 'bytes')
